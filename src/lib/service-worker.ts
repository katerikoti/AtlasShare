/**
 * The service worker is generated as a static route so its cache policy can be
 * unit-tested alongside the app.
 *
 * Keep `SW_CACHE_VERSION` in step with changes to the worker's caching logic.
 * A new version is how the update prompt and activate-time cleanup discover an
 * old cache. Next's hashed build assets are versioned by their own filenames.
 */
export const SW_CACHE_VERSION = "2026-10-27.2";
export const SW_CACHE_PREFIX = "atlas-pwa-";
export const SW_SHELL_CACHE = `${SW_CACHE_PREFIX}shell-${SW_CACHE_VERSION}`;
export const SW_RUNTIME_CACHE_PREFIX = `${SW_CACHE_PREFIX}runtime-`;
export const SW_RUNTIME_CACHE = `${SW_RUNTIME_CACHE_PREFIX}${SW_CACHE_VERSION}`;

/** The self-contained HTML response served when a navigation fails offline. */
export const OFFLINE_URL = "/offline";

/**
 * Public, self-contained files kept in the install-time shell cache. Country
 * geometry is public but is cached on demand with the other static assets.
 */
export const PRECACHE_ASSETS = [
  OFFLINE_URL,
  "/icon.svg",
  "/manifest.webmanifest",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/maskable-512.png",
] as const;

/** Only content-hashed Next chunks and the public icon set are cached. */
export const CACHEABLE_PREFIXES = ["/_next/static/", "/icons/"] as const;

/** Exact public files that are safe to cache despite not matching a prefix. */
export const CACHEABLE_PATHS = [
  "/map/countries.json",
  "/icon.svg",
  "/manifest.webmanifest",
] as const;

/**
 * Paths that must never be written to a cache. Navigation requests are handled
 * separately and are always network-only, but this list keeps the intent
 * explicit for any future non-navigation fetch handling.
 */
export const PRIVATE_PREFIXES = [
  "/api",
  "/invite",
  "/account",
  "/shared",
  "/map",
  "/sign-in",
  "/sign-up",
  "/forgot-password",
  "/reset-password",
] as const;

export function isPrivatePath(pathname: string): boolean {
  return PRIVATE_PREFIXES.some(
    (prefix) => pathname === prefix || pathname.startsWith(`${prefix}/`),
  );
}

/**
 * The fetch handler's allowlist. The exact public paths are checked before the
 * private-prefix list because `/map/countries.json` is public despite living
 * under `/map`.
 */
export function isCacheableAsset(pathname: string): boolean {
  if ((CACHEABLE_PATHS as readonly string[]).includes(pathname)) return true;
  if (isPrivatePath(pathname)) return false;
  return CACHEABLE_PREFIXES.some((prefix) => pathname.startsWith(prefix));
}

/**
 * Render the classic service worker script served at `/sw.js`.
 *
 * Security invariants:
 * - Navigation requests go to the network and are never cached. A failed
 *   navigation gets the public offline page.
 * - Only GET requests from this origin are considered.
 * - Non-navigation responses are written only when the path matches the
 *   allowlist and the response is public (no `private`/`no-store`).
 */
export function renderServiceWorker(): string {
  const precacheAssets = JSON.stringify(PRECACHE_ASSETS);
  const cacheablePrefixes = JSON.stringify(CACHEABLE_PREFIXES);
  const cacheablePaths = JSON.stringify(CACHEABLE_PATHS);
  const privatePrefixes = JSON.stringify(PRIVATE_PREFIXES);

  return `/* Generated by src/lib/service-worker.ts. Do not edit the response by hand. */
const CACHE_VERSION = ${JSON.stringify(SW_CACHE_VERSION)};
const CACHE_PREFIX = ${JSON.stringify(SW_CACHE_PREFIX)};
const SHELL_CACHE = ${JSON.stringify(SW_SHELL_CACHE)};
const RUNTIME_CACHE = ${JSON.stringify(SW_RUNTIME_CACHE)};
const RUNTIME_CACHE_PREFIX = ${JSON.stringify(SW_RUNTIME_CACHE_PREFIX)};
const OFFLINE_URL = ${JSON.stringify(OFFLINE_URL)};
const PRECACHE_ASSETS = ${precacheAssets};
const CACHEABLE_PREFIXES = ${cacheablePrefixes};
const CACHEABLE_PATHS = ${cacheablePaths};
const PRIVATE_PREFIXES = ${privatePrefixes};

function isPrivatePath(pathname) {
  return PRIVATE_PREFIXES.some(
    (prefix) => pathname === prefix || pathname.startsWith(prefix + "/"),
  );
}

function isCacheableAsset(pathname) {
  if (CACHEABLE_PATHS.includes(pathname)) return true;
  if (isPrivatePath(pathname)) return false;
  return CACHEABLE_PREFIXES.some((prefix) => pathname.startsWith(prefix));
}

async function putPublicResponse(cache, request, response) {
  if (!response || !response.ok || response.status !== 200) return;
  const cacheControl = response.headers.get("cache-control") || "";
  if (cacheControl.includes("private") || cacheControl.includes("no-store")) {
    return;
  }
  await cache.put(request, response.clone());
}

async function precacheShell() {
  const cache = await caches.open(SHELL_CACHE);
  const offline = await fetch(OFFLINE_URL, { cache: "reload" });
  if (!offline.ok) {
    throw new Error("The offline page could not be cached.");
  }
  await cache.put(OFFLINE_URL, offline);

  await Promise.allSettled(
    PRECACHE_ASSETS.filter((url) => url !== OFFLINE_URL).map(async (url) => {
      const response = await fetch(url, { cache: "reload" });
      if (response.ok) await cache.put(url, response);
    }),
  );
}

async function navigationResponse(request) {
  // Never cache a navigation response. Authenticated HTML must not be replayed
  // from the service worker after sign-out or for another account.
  try {
    return await fetch(request);
  } catch {
    const offline = await caches.match(OFFLINE_URL);
    if (offline) return offline;
    return new Response("You are offline.", {
      status: 503,
      headers: {
        "Content-Type": "text/plain; charset=utf-8",
        "Cache-Control": "no-store",
      },
    });
  }
}

async function assetResponse(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(RUNTIME_CACHE);
    await putPublicResponse(cache, request, response);
  }
  return response;
}

self.addEventListener("install", (event) => {
  event.waitUntil(precacheShell());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter(
            (key) =>
              key.startsWith(CACHE_PREFIX) &&
              key !== SHELL_CACHE &&
              key !== RUNTIME_CACHE,
          )
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  const type = event.data && event.data.type;
  if (type === "SKIP_WAITING") {
    self.skipWaiting();
  }
  if (type === "CLEAR_RUNTIME_CACHES") {
    event.waitUntil(caches.delete(RUNTIME_CACHE));
  }
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // All documents — public marketing pages and private app pages alike — stay
  // network-only. The only offline response is the public offline shell.
  if (request.mode === "navigate") {
    event.respondWith(navigationResponse(request));
    return;
  }

  // This allowlist is the only path that can write to the runtime cache.
  if (isCacheableAsset(url.pathname)) {
    event.respondWith(assetResponse(request));
    return;
  }

  // Everything else, including /api/* and invitation paths, is left alone.
  if (isPrivatePath(url.pathname)) return;
});
`;
}
