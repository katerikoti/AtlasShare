const regionsByCode: Record<string, CountryRegion> = {};

for (const region of countryRegionOrder) {
  for (const code of countryRegionGroups[region]) {
    if (regionsByCode[code]) {
      throw new Error(`Country ${code} is assigned to more than one region.`);
    }
    regionsByCode[code] = region;
  }
}

export const countryRegions: Readonly<Record<string, CountryRegion>> =
  Object.freeze(regionsByCode);
